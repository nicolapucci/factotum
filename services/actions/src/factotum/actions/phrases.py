"""What the assistant says about an action, in the language of the person.

The answer to a request is not generated by a model: it is one of a few sentences that say exactly
what happened (done, not allowed, needs an approval, could not be reached), in the language the
person spoke. A model reads that language out of the message, and this is where it becomes words.
English and Italian are here; another language is answered in English until somebody adds it, and
a test says that no sentence is missing from any of them.

What a skill says of its own result (the ``message`` of a run) is said as it is, and so is the
question a model wrote to ask for a yes: those are in the language they were written in.
"""

from enum import StrEnum

from factotum.contracts.authorization import Reason

DEFAULT_LANGUAGE = "en"


class Say(StrEnum):
    DONE = "done"
    DRY_RUN = "dry_run"
    CANCELLED = "cancelled"
    CONFIRM = "confirm"
    NEEDS_VALUES = "needs_values"
    WHICH_DEVICE = "which_device"
    NO_DEVICE = "no_device"
    NOT_ALLOWED_HERE = "not_allowed_here"
    NOT_ALLOWED = "not_allowed"
    APPROVAL_UNAVAILABLE = "approval_unavailable"
    APPROVAL_DENIED = "approval_denied"
    APPROVAL_EXPIRED = "approval_expired"
    UNKNOWN_DEVICE = "unknown_device"
    NOT_ENABLED = "not_enabled"
    FAILED = "failed"
    RUNNER_UNAVAILABLE = "runner_unavailable"
    COMMAND_FAILED = "command_failed"


_CATALOG: dict[str, dict[Say, str]] = {
    "en": {
        Say.DONE: "Done.",
        Say.DRY_RUN: "Dry run: I would have run {skill}, and nothing was done.",
        Say.CANCELLED: "Okay, I will not do it.",
        Say.CONFIRM: "Do you want me to run {skill}?",
        Say.NEEDS_VALUES: "I still need: {names}.",
        Say.WHICH_DEVICE: "Which one do you mean: {names}?",
        Say.NO_DEVICE: "There is no device set up for that.",
        Say.NOT_ALLOWED_HERE: "This device is not allowed to do that.",
        Say.NOT_ALLOWED: "I cannot do that.",
        Say.APPROVAL_UNAVAILABLE: (
            "That needs somebody's approval, and I have no way to ask for it."
        ),
        Say.APPROVAL_DENIED: "It was not approved.",
        Say.APPROVAL_EXPIRED: "Nobody approved it in time.",
        Say.UNKNOWN_DEVICE: "I do not know this device, so I did nothing.",
        Say.NOT_ENABLED: "That is not available any more.",
        Say.FAILED: "It did not work.",
        Say.RUNNER_UNAVAILABLE: "I cannot run that right now.",
        Say.COMMAND_FAILED: "I asked the device, and it did not do it.",
    },
    "it": {
        Say.DONE: "Fatto.",
        Say.DRY_RUN: "Prova a vuoto: avrei eseguito {skill}, e non è stato fatto nulla.",
        Say.CANCELLED: "Va bene, non lo faccio.",
        Say.CONFIRM: "Vuoi che esegua {skill}?",
        Say.NEEDS_VALUES: "Mi serve ancora: {names}.",
        Say.WHICH_DEVICE: "Quale intendi: {names}?",
        Say.NO_DEVICE: "Non c'è nessun dispositivo configurato per questo.",
        Say.NOT_ALLOWED_HERE: "Questo dispositivo non può farlo.",
        Say.NOT_ALLOWED: "Non posso farlo.",
        Say.APPROVAL_UNAVAILABLE: ("Serve l'approvazione di qualcuno e non ho modo di chiederla."),
        Say.APPROVAL_DENIED: "Non è stato approvato.",
        Say.APPROVAL_EXPIRED: "Nessuno l'ha approvato in tempo.",
        Say.UNKNOWN_DEVICE: "Non conosco questo dispositivo, quindi non ho fatto nulla.",
        Say.NOT_ENABLED: "Non è più disponibile.",
        Say.FAILED: "Non ha funzionato.",
        Say.RUNNER_UNAVAILABLE: "Non posso eseguirlo in questo momento.",
        Say.COMMAND_FAILED: "L'ho chiesto al dispositivo, ma non l'ha fatto.",
    },
}

LANGUAGES = frozenset(_CATALOG)

_NOT_ALLOWED_HERE = {Reason.EXCEEDS_DEVICE_MAX_EFFECT, Reason.SKILL_NOT_ALLOWED_ON_DEVICE}
_NOT_TO_BE_TOLD = {Reason.CROSS_TENANT, Reason.SKILL_NOT_VISIBLE, Reason.TARGET_NOT_VISIBLE}


def language_of(code: str | None) -> str:
    """The language to answer in, for the one a model read from the message: the same if there are
    words for it, English if there are not."""
    return code if code in _CATALOG else DEFAULT_LANGUAGE


def say(language: str | None, key: Say, /, **fields: str) -> str:
    """A sentence, in the language if it is known and in English if it is not."""
    return _CATALOG[language_of(language)][key].format_map(fields)


def refusal(language: str | None, reasons: tuple[Reason, ...]) -> str:
    """Why an action is not allowed, in a way that says no more than the person may know: that a
    device is not allowed to do it, or plainly that it cannot be done (a skill or a device the
    person may not see is not to be told to exist)."""
    given = set(reasons)
    hidden = bool(_NOT_TO_BE_TOLD & given)
    key = Say.NOT_ALLOWED_HERE if _NOT_ALLOWED_HERE & given and not hidden else Say.NOT_ALLOWED
    return say(language, key)
